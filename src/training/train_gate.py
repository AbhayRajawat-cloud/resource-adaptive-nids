"""
Stage 3: Training routines for Self-Supervised Student Gating Regressors.

Constraints & Specifications:
- Freezes client k's trained Autoencoder weights.
- Generates Teacher log-MSE targets for client k's benign training split:
      y_i^gate = log(MSE(x_i; AE_k) + 1e-6)
- Trains GatingRegressor_k using Adam optimizer (lr=1e-3, weight_decay=1e-5, batch_size=64, max_epochs=40)
  and Smooth L1 (Huber) Loss (delta=1.0).
- Early stopping monitors Huber loss on client k's benign validation flows,
  evaluated against targets generated by passing benign validation flows through frozen AE_k.
- Calibrates log-scale gate threshold tau_gate_k = Quantile_0.99(e_hat_val_benign)
  on client k's benign validation predictions.
- Saves model weights to outputs/checkpoints/stage3/client_{k}_gate.pt.
- Saves threshold artifacts to outputs/checkpoints/stage3/client_{k}_thresholds.json.
"""

from pathlib import Path
from typing import Dict, Any, Tuple
import copy
import json
import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import TensorDataset, DataLoader
from torch.optim.lr_scheduler import ReduceLROnPlateau

from src.models.autoencoder import Autoencoder
from src.models.gate import GatingRegressor
from src.training.train_autoencoder import compute_bootstrap_ci


def generate_teacher_targets(
    model_ae: Autoencoder,
    features: np.ndarray,
    device: torch.device,
    batch_size: int = 256,
) -> np.ndarray:
    """
    Generate teacher log-MSE targets: y_i^gate = log(MSE(x_i; AE) + 1e-6)
    """
    model_ae.eval()
    t_feat = torch.tensor(features, dtype=torch.float32)
    loader = DataLoader(TensorDataset(t_feat), batch_size=batch_size, shuffle=False)

    log_targets = []
    with torch.no_grad():
        for (batch_x,) in loader:
            batch_x = batch_x.to(device)
            recon = model_ae(batch_x)
            mse = Autoencoder.compute_mse(batch_x, recon)
            log_target = torch.log(mse + 1e-6)
            log_targets.append(log_target.cpu().numpy())

    return np.concatenate(log_targets)


def train_client_gate(
    client_id: int,
    model_ae: Autoencoder,
    x_train_benign: np.ndarray,
    x_val_benign: np.ndarray,
    tau_ae: float,
    tau_ae_ci_low: float,
    tau_ae_ci_high: float,
    device: torch.device,
    config: Dict[str, Any] = None,
    save_dir: Path = None,
) -> Dict[str, Any]:
    """
    Train student GatingRegressor predicting teacher AE's log-reconstruction error.
    """
    cfg = config or {}
    batch_size = cfg.get("batch_size", 64)
    lr = cfg.get("lr", 1e-3)
    weight_decay = cfg.get("weight_decay", 1e-5)
    max_epochs = cfg.get("max_epochs", 40)
    min_epochs = cfg.get("min_epochs", 10)
    patience = cfg.get("patience", 5)

    max_train_samples = cfg.get("max_train_samples", 50000)
    if len(x_train_benign) > max_train_samples:
        rng = np.random.default_rng(42 + client_id)
        sub_idx = rng.choice(len(x_train_benign), size=max_train_samples, replace=False)
        train_features = x_train_benign[sub_idx]
    else:
        train_features = x_train_benign

    # Generate teacher targets using frozen AE
    y_gate_train = generate_teacher_targets(model_ae, train_features, device)
    y_gate_val = generate_teacher_targets(model_ae, x_val_benign, device)

    t_train_x = torch.tensor(train_features, dtype=torch.float32)
    t_train_y = torch.tensor(y_gate_train, dtype=torch.float32).unsqueeze(1)

    t_val_x = torch.tensor(x_val_benign, dtype=torch.float32)
    t_val_y = torch.tensor(y_gate_val, dtype=torch.float32).unsqueeze(1)

    train_loader = DataLoader(
        TensorDataset(t_train_x, t_train_y), batch_size=batch_size, shuffle=True
    )
    val_loader = DataLoader(
        TensorDataset(t_val_x, t_val_y), batch_size=batch_size * 2, shuffle=False
    )

    # Initialize Gating Regressor
    model_gate = GatingRegressor(input_dim=train_features.shape[1]).to(device)
    optimizer = torch.optim.Adam(model_gate.parameters(), lr=lr, weight_decay=weight_decay)
    scheduler = ReduceLROnPlateau(optimizer, mode="min", factor=0.5, patience=3)
    criterion = nn.SmoothL1Loss(beta=1.0)  # Huber loss with delta=1.0

    best_val_loss = float("inf")
    best_weights = None
    best_epoch = 0
    patience_counter = 0
    history = {"train_loss": [], "val_loss": [], "lr": []}

    for epoch in range(1, max_epochs + 1):
        model_gate.train()
        running_train_loss = 0.0
        n_train_samples = 0

        for batch_x, batch_y in train_loader:
            batch_x, batch_y = batch_x.to(device), batch_y.to(device)
            optimizer.zero_grad()
            preds = model_gate(batch_x)
            loss = criterion(preds, batch_y)
            loss.backward()
            optimizer.step()

            running_train_loss += loss.item() * len(batch_x)
            n_train_samples += len(batch_x)

        epoch_train_loss = running_train_loss / n_train_samples

        # Validation phase
        model_gate.eval()
        running_val_loss = 0.0
        n_val_samples = 0

        with torch.no_grad():
            for batch_x, batch_y in val_loader:
                batch_x, batch_y = batch_x.to(device), batch_y.to(device)
                preds = model_gate(batch_x)
                loss = criterion(preds, batch_y)
                running_val_loss += loss.item() * len(batch_x)
                n_val_samples += len(batch_x)

        epoch_val_loss = running_val_loss / n_val_samples
        current_lr = optimizer.param_groups[0]["lr"]

        history["train_loss"].append(epoch_train_loss)
        history["val_loss"].append(epoch_val_loss)
        history["lr"].append(current_lr)

        scheduler.step(epoch_val_loss)

        if epoch_val_loss < best_val_loss:
            best_val_loss = epoch_val_loss
            best_epoch = epoch
            best_weights = copy.deepcopy(model_gate.state_dict())
            patience_counter = 0
        else:
            patience_counter += 1

        if epoch >= min_epochs and patience_counter >= patience:
            break

    # Restore best weights
    model_gate.load_state_dict(best_weights)
    model_gate.eval()

    # Calibrate log-scale gate threshold tau_gate_k = Quantile_0.99(e_hat_val_benign)
    with torch.no_grad():
        val_preds = []
        for batch_x, _ in val_loader:
            batch_x = batch_x.to(device)
            preds = model_gate(batch_x)
            val_preds.append(preds.squeeze(1).cpu().numpy())
        val_preds_arr = np.concatenate(val_preds)

    tau_gate, tau_gate_ci_low, tau_gate_ci_high = compute_bootstrap_ci(
        val_preds_arr, quantile=0.99, n_bootstrap=1000, seed=42 + client_id
    )

    # Save checkpoints and threshold artifacts
    if save_dir:
        save_dir = Path(save_dir)
        save_dir.mkdir(parents=True, exist_ok=True)
        torch.save(best_weights, save_dir / f"client_{client_id:02d}_gate.pt")

        threshold_artifact = {
            "client_id": client_id,
            "tau_ae": float(tau_ae),
            "tau_ae_95ci": [float(tau_ae_ci_low), float(tau_ae_ci_high)],
            "tau_gate": float(tau_gate),
            "tau_gate_95ci": [float(tau_gate_ci_low), float(tau_gate_ci_high)],
            "calibration_samples_benign_val": len(val_preds_arr),
        }
        with open(save_dir / f"client_{client_id:02d}_thresholds.json", "w") as f:
            json.dump(threshold_artifact, f, indent=2)

    return {
        "model": model_gate,
        "best_epoch": best_epoch,
        "best_val_loss": best_val_loss,
        "tau_gate": tau_gate,
        "tau_gate_ci_low": tau_gate_ci_low,
        "tau_gate_ci_high": tau_gate_ci_high,
        "history": history,
    }
